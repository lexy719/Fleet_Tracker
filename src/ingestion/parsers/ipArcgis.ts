import { hashString } from "../../regulations/decisionInputs";
import { candidateContentHash, emptyFields, field, geometryField, type ParsedCandidate } from "../candidate";
import { fold, normalizeWs } from "../text";
import type { CandidateCategory, ExtractionError, ParseOutput, RawSnapshot } from "../types";

/*
 * IP «Viajar na Estrada» ArcGIS layers (Acidentes / Outras Ocorrências / Condicionamentos).
 * Fields (verified from layer metadata): tipo, estado, datainicio, dataobservacao, datafim
 * (epoch ms), commentsummary, description (road), pkbegin, direction, distrito, concelho,
 * latitude, longitude.
 */

export const IP_ARCGIS_PARSER_VERSION = 1;

/** DATEX-style `tipo` codes → category. Unknown codes stay OTHER (never guessed). */
const CATEGORY: Record<string, CandidateCategory> = {
  Accident: "INCIDENT",
  GenericIncident: "INCIDENT",
  MaintenanceWorks: "ROADWORKS",
  ConstructionWorks: "ROADWORKS",
  PoorRoadInfrastructure: "OBSTRUCTION",
  Activities: "OTHER",
  AnimalPresenceObstruction: "OBSTRUCTION",
  EnvironmentalObstruction: "OBSTRUCTION",
  EquipmentDamageObstruction: "OBSTRUCTION",
  GeneralObstruction: "OBSTRUCTION",
  VehicleObstruction: "OBSTRUCTION",
};

/** Prose that suggests a closure. Only raises a review flag — never sets the category. */
const CLOSURE_WORDS = /\b(cortad[oa]s?|corte (total|da circulacao|ao transito)|interdit[oa]|encerrad[oa])\b/;

type Feature = { attributes?: Record<string, unknown>; geometry?: { x?: unknown; y?: unknown } };

const num = (v: unknown): number | undefined => (typeof v === "number" && Number.isFinite(v) ? v : undefined);
const str = (v: unknown): string | undefined => (typeof v === "string" && v.trim() ? normalizeWs(v) : undefined);

export function parseIpArcgis(snapshot: RawSnapshot): ParseOutput {
  const errors: ExtractionError[] = [];
  let json: unknown;
  try {
    json = JSON.parse(snapshot.body);
  } catch (e) {
    return { candidates: [], errors: [{ sourceId: snapshot.sourceId, snapshotId: snapshot.id, kind: "PARSE_ERROR", message: `JSON inválido: ${String(e)}` }], recordCount: 0 };
  }
  const root = json as { features?: unknown; error?: { message?: string } };
  if (root.error) {
    return { candidates: [], errors: [{ sourceId: snapshot.sourceId, snapshotId: snapshot.id, kind: "PARSE_ERROR", message: `ArcGIS error: ${root.error.message ?? "?"}` }], recordCount: 0 };
  }
  if (!Array.isArray(root.features)) {
    return { candidates: [], errors: [{ sourceId: snapshot.sourceId, snapshotId: snapshot.id, kind: "PARSE_ERROR", message: "resposta sem «features»" }], recordCount: 0 };
  }

  const candidates: ParsedCandidate[] = [];
  let newest = -Infinity;
  const seen = new Set<string>();
  for (const [i, f] of (root.features as Feature[]).entries()) {
    const a = f?.attributes;
    if (!a || typeof a !== "object") {
      errors.push({ sourceId: snapshot.sourceId, snapshotId: snapshot.id, kind: "PARSE_ERROR", message: `feature ${i} sem atributos` });
      continue;
    }
    const tipo = str(a.tipo);
    const road = str(a.description);
    const start = num(a.datainicio);
    const observed = num(a.dataobservacao);
    const end = num(a.datafim);
    const lat = num(f.geometry?.y) ?? num(a.latitude);
    const lng = num(f.geometry?.x) ?? num(a.longitude);
    if (observed !== undefined) newest = Math.max(newest, observed);
    if (start !== undefined) newest = Math.max(newest, start);

    // objectid is regenerated by the service; identify a record by its content instead.
    const naturalKey = [tipo ?? "?", road ?? "?", start ?? "?", lat?.toFixed(5) ?? "?", lng?.toFixed(5) ?? "?"].join("|");
    let externalId = `ev-${hashString(naturalKey)}`;
    if (seen.has(externalId)) externalId = `${externalId}-${i}`;
    seen.add(externalId);

    const fields = emptyFields();
    const issues: string[] = [];
    if (tipo) {
      const cat = CATEGORY[tipo];
      fields.category = cat
        ? field("VERIFIED", cat, `tipo = ${tipo}`)
        : field("VERIFIED", "OTHER", `tipo = ${tipo}`, "Código não mapeado — tratado como OTHER.");
    } else issues.push("registo sem «tipo»");
    if (road) fields.roads = field("VERIFIED", [road.replace(/\s+/g, "")], "description");
    const where = [str(a.concelho), str(a.distrito)].filter(Boolean).join(", ");
    const pk = num(a.pkbegin);
    if (where || pk !== undefined) {
      fields.locationText = field("VERIFIED", `${where}${pk !== undefined ? ` · PK ${pk}` : ""}`, "concelho, distrito, pkbegin");
    }
    if (lat !== undefined && lng !== undefined && Math.abs(lat) <= 90 && Math.abs(lng) <= 180) {
      fields.geometry = geometryField("VERIFIED", { kind: "point", point: [lat, lng] }, "VERIFIED", "geometria do ponto", "Só um ponto (PK) — extensão do troço afetado não indicada.");
    } else issues.push("registo sem coordenadas válidas");
    if (start !== undefined) {
      fields.validity = field(
        "VERIFIED",
        { start: new Date(start).toISOString(), ...(end !== undefined ? { end: new Date(end).toISOString() } : {}) },
        "datainicio / datafim",
        end === undefined ? "Sem data de fim indicada." : new Date(end).getUTCFullYear() >= 2050 ? "Data de fim muito distante — provável marcador de «sem fim» (interpretação)." : undefined,
      );
    }
    const dir = str(a.direction);
    if (dir) fields.direction = field("VERIFIED", dir, "direction");
    const summary = str(a.commentsummary);
    if (summary) fields.description = field("VERIFIED", summary, "commentsummary");
    if (summary && CLOSURE_WORDS.test(fold(summary))) {
      issues.push("O texto menciona corte/interdição, mas o tipo estruturado não é um corte — requer revisão humana.");
    }
    const estado = str(a.estado);
    if (estado && estado !== "ativo") issues.push(`estado = ${estado}`);

    const title = [road, tipo, str(a.concelho)].filter(Boolean).join(" · ") || "Evento IP sem título";
    candidates.push({
      id: `${snapshot.sourceId}:${externalId}`,
      sourceId: snapshot.sourceId,
      externalId,
      title,
      fields,
      extraction: { kind: "parser", parser: "ip-arcgis-events", version: IP_ARCGIS_PARSER_VERSION },
      snapshotId: snapshot.id,
      contentHash: candidateContentHash(title, fields),
      issues,
    });
  }
  return {
    candidates,
    errors,
    recordCount: root.features.length,
    ...(Number.isFinite(newest) ? { publishedAt: new Date(newest).toISOString(), publishedAtBasis: "máximo de dataobservacao/datainicio dos registos" } : {}),
  };
}
